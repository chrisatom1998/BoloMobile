import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const source = ['scenes.ts', 'additional-scenes.ts']
  .map((fileName) => readFileSync(join(root, 'src/data', fileName), 'utf8'))
  .join('\n');
const outputDirectory = join(root, 'assets/audio/hindi-core');
const generatedModule = join(root, 'src/data/offline-hindi-audio.ts');
const hindi = /['`]([^'`]*[\u0900-\u097F][^'`]*)['`]/gu;
const texts = [...new Set([...source.matchAll(hindi)].map((match) => match[1].trim()).filter(Boolean))].sort();

mkdirSync(outputDirectory, { recursive: true });
const entries = [];
for (const text of texts) {
  const name = createHash('sha256').update(text).digest('hex').slice(0, 16);
  const target = join(outputDirectory, `${name}.m4a`);
  if (!existsSync(target)) {
    const temporary = join(outputDirectory, `${name}.aiff`);
    execFileSync('say', ['-v', 'Lekha', '-r', '155', '-o', temporary, text]);
    execFileSync('afconvert', [temporary, target, '-f', 'm4af', '-d', 'aac', '-b', '64000']);
    rmSync(temporary, { force: true });
  }
  entries.push(`  ${JSON.stringify(text)}: require(${JSON.stringify(`../../assets/audio/hindi-core/${name}.m4a`)}),`);
}

writeFileSync(generatedModule, `// Generated by scripts/generate-offline-hindi-audio.mjs.\n// Fixed lesson audio is bundled so it never requires consent or a network request.\nexport const offlineHindiAudio: Record<string, number> = {\n${entries.join('\n')}\n};\n`);
console.log(`Generated ${entries.length} bundled Hindi audio clips.`);
